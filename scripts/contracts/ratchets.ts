/** The `op` discriminant of every member of the `Effect` union in `cards/ability.ts`. */
export function effectOps(path: string, source: string): string[] {
  const file = ts.createSourceFile(path, source, ts.ScriptTarget.Latest, true);
  const ops: string[] = [];
  let found = false;
  for (const statement of file.statements) {
    if (!ts.isTypeAliasDeclaration(statement) || statement.name.text !== 'Effect') continue;
    found = true;
    const members = ts.isUnionTypeNode(statement.type) ? statement.type.types : [statement.type];
    for (const member of members) {
      if (!ts.isTypeLiteralNode(member))
        throw new Error(
          `${path}: \`Effect\` member \`${member.getText(file).slice(0, 60)}\` is not an object type literal, so its op cannot be read`,
        );
      const op = member.members.find(
        (entry): entry is ts.PropertySignature =>
          ts.isPropertySignature(entry) && entry.name.getText(file) === 'op',
      );
      const literal =
        op?.type !== undefined && ts.isLiteralTypeNode(op.type) ? op.type.literal : undefined;
      if (literal === undefined || !ts.isStringLiteral(literal))
        throw new Error(`${path}: an \`Effect\` member has no string-literal \`op\``);
      ops.push(literal.text);
    }
  }
  if (!found) throw new Error(`${path}: no \`Effect\` type alias`);
  return ops;
}

export interface OpRatchet {
  errors: string[];
  warnings: string[];
  /** Ops on HEAD that equal a card-name slug (the list that may not grow). */
  cardNamed: string[];
}

/** Composite names a primitive should not have: "AndThen" ops are two primitives glued together. */
const COMPOSITE = /[a-z0-9](And|Then)(?=[A-Z0-9]|$)/;

export function checkCardNamedOps(options: {
  baseOps: readonly string[] | undefined;
  headOps: readonly string[];
  slugs: Readonly<Record<string, string>>;
}): OpRatchet {
  const base = new Set(options.baseOps ?? []);
  const errors: string[] = [];
  const warnings: string[] = [];
  const cardNamed = options.headOps.filter((op) => Object.hasOwn(options.slugs, op)).sort();
  for (const op of options.headOps) {
    if (base.has(op)) continue;
    if (Object.hasOwn(options.slugs, op))
      errors.push(
        `new Effect op \`${op}\` is the slug of card "${options.slugs[op]}". Model the card from existing primitives, or add a general primitive named for what it does.`,
      );
    else if (COMPOSITE.test(op))
      warnings.push(
        `new Effect op \`${op}\` contains And/Then; prefer composing two primitives over one composite op.`,
      );
  }
  return { errors, warnings, cardNamed };
}

// ---------------------------------------------------------------------------
// notExecutableInCi
// ---------------------------------------------------------------------------

/**
 * Manifest test IDs marked `notExecutableInCi`, keyed `oracleId::id` so moving an ID between
 * clauses is not growth. Two forms are read: a clause's `notExecutableInCi: string[]`, and an
 * `engineTestIds` entry written as `{ id, notExecutableInCi: true }`.
 */
export function notExecutableInCiIds(manifestText: string): Set<string> {
  const manifest = JSON.parse(manifestText) as {
    cards?: Record<string, { clauses?: Record<string, unknown>[] }>;
  };
  const marked = new Set<string>();
  for (const [oracleId, card] of Object.entries(manifest.cards ?? {})) {
    for (const clause of card.clauses ?? []) {
      const listed = clause['notExecutableInCi'];
      if (Array.isArray(listed))
        for (const id of listed) if (typeof id === 'string') marked.add(`${oracleId}::${id}`);
      const tests = clause['engineTestIds'];
      if (Array.isArray(tests))
        for (const entry of tests) {
          if (entry !== null && typeof entry === 'object') {
            const object = entry as Record<string, unknown>;
            if (object['notExecutableInCi'] === true && typeof object['id'] === 'string')
              marked.add(`${oracleId}::${object['id']}`);
          }
        }
    }
  }
  return marked;
}

export function checkNotExecutableInCi(options: {
  baseManifest: string | undefined;
  headManifest: string;
}): { errors: string[]; count: number } {
  const base =
    options.baseManifest === undefined
      ? new Set<string>()
      : notExecutableInCiIds(options.baseManifest);
  const head = notExecutableInCiIds(options.headManifest);
  const errors = [...head]
    .filter((id) => !base.has(id))
    .sort()
    .map(
      (id) =>
        `manifest test ID \`${id}\` is newly marked notExecutableInCi; that list may not grow. Make the test run from a committed fixture instead.`,
    );
  return { errors, count: head.size };
}

// ---------------------------------------------------------------------------
// Base commit
// ---------------------------------------------------------------------------

export interface GitReader {
  /** Whether `sha` names a commit in this clone. */
  hasCommit: (sha: string) => boolean;
  /** HEAD's first parent, if there is one. */
  firstParent: () => string | undefined;
}

export type BaseResolution =
  { kind: 'base'; sha: string; notice?: string } | { kind: 'none'; notice: string };

/**
 * The same fallback `ci.yml` uses for the promotion check: the pull request's base SHA, or for a
 * push the event's `before` SHA. When that is empty, all zeros (a new branch) or not in the clone,
 * compare with HEAD's first parent; with no parent at all there is nothing to compare.
 */
export function resolveBase(candidate: string | undefined, git: GitReader): BaseResolution {
  const value = candidate?.trim() ?? '';
  if (value !== '' && !/^0+$/.test(value) && git.hasCommit(value))
    return { kind: 'base', sha: value };
  const parent = git.firstParent();
  if (parent === undefined)
    return {
      kind: 'none',
      notice: 'No prior commit exists; skipping base-relative ratchet comparison.',
    };
  return {
    kind: 'base',
    sha: parent,
    notice: "Base SHA unavailable; comparing ratchets with HEAD's first parent.",
  };
}
