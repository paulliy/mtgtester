import ts from 'typescript';

/**
 * Ratchets (ADR 0034 decision 9): lists that may shrink but must not grow, checked against the
 * base commit of a pull request.
 *
 * 1. Card-named `Effect` ops. An op named after one card (`angelGrace`, `masterOfCeremonies`) is
 *    engine code that serves one card; a new one is rejected, and removing one is always fine.
 *    "Named after a card" means equal to the camelCase slug of a name in the pinned Oracle fixtures
 *    or the verification manifest (`scripts/card-name-slugs.json`).
 * 2. Manifest test IDs marked `notExecutableInCi` (they run only with the gitignored bulk file).
 *
 * Everything here is a pure function over file text so the checks can be proven to fire.
 */

// ---------------------------------------------------------------------------
// Card-name slugs
// ---------------------------------------------------------------------------

function camelCase(text: string): string {
  const words = text
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .match(/[A-Za-z0-9]+/g);
  if (words === null) return '';
  return words
    .map((word, index) =>
      index === 0 ? word.toLowerCase() : word.charAt(0).toUpperCase() + word.slice(1).toLowerCase(),
    )
    .join('');
}

/**
 * The slugs a card name can appear as in an op name: camelCase of each face, of the part before a
 * legend's comma ("Kambal, Consul of Allocation" is `kambal`), each with the possessive dropped
 * ("Angel's Grace" is `angelGrace`) and with the apostrophe merely removed (`angelsGrace`).
 */
export function cardNameSlugs(name: string): string[] {
  const slugs = new Set<string>();
  for (const face of name.split('//')) {
    const trimmed = face.trim();
    for (const form of [trimmed, trimmed.split(',')[0]!]) {
      for (const variant of [form.replace(/['’]s\b/g, ''), form.replace(/['’]/g, '')]) {
        const slug = camelCase(variant);
        if (slug !== '') slugs.add(slug);
      }
    }
  }
  return [...slugs];
}

/**
 * Names of cards in a pinned Oracle fixture or the manifest: any object with a string `name` that
 * also has an Oracle identity or a type line. The fixtures use several envelopes (`cards[].card`,
 * `cards[]`, `projection`), so the walk does not depend on one.
 */
export function cardNamesIn(value: unknown, into: Set<string> = new Set()): Set<string> {
  if (Array.isArray(value)) for (const entry of value) cardNamesIn(entry, into);
  else if (value !== null && typeof value === 'object') {
    const object = value as Record<string, unknown>;
    if (
      typeof object['name'] === 'string' &&
      ('oracleId' in object ||
        'oracle_id' in object ||
        'typeLine' in object ||
        'type_line' in object)
    )
      into.add(object['name']);
    for (const entry of Object.values(object)) cardNamesIn(entry, into);
  }
  return into;
}

/** Slug to the first (alphabetical) card name that produces it. */
export function slugTable(names: Iterable<string>): Record<string, string> {
  const table: Record<string, string> = {};
  for (const name of [...new Set(names)].sort()) {
    for (const slug of cardNameSlugs(name)) table[slug] ??= name;
  }
  return Object.fromEntries(Object.entries(table).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

export interface SlugFile {
  schemaVersion: 1;
  note: string;
  slugs: Record<string, string>;
}

