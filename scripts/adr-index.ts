/**
 * Regenerates the table in `docs/decisions/README.md` from the ADR files themselves, so the index
 * cannot drift from the decisions it lists.
 *
 *   bun run adr:index            rewrite the table
 *   bun run adr:index --check    fail if the table is stale, two ADRs share a number, or an ADR's
 *                                status line is missing or not in the standard form
 *
 * Every ADR is `docs/decisions/NNNN-slug.md`. Its header (everything before the first `## `) holds
 * one status line in the form
 *
 *   Status: <Accepted|Proposed|Completed|Superseded by NNNN> (YYYY-MM-DD)
 *
 * with the date optional only when the ADR never recorded one. Qualifiers go on a following
 * `Status note:` line. Header lines that start with "Supersedes", "Amends", "Superseded in part
 * by" or "Amended by" and link to another ADR fill the "Changed by" column of the ADR they change.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { format } from 'prettier';

const ROOT = join(import.meta.dirname, '..');
const DIR = join(ROOT, 'docs', 'decisions');
const README = join(DIR, 'README.md');
const START = '<!-- adr-index:start (generated by `bun run adr:index`; do not edit by hand) -->';
const END = '<!-- adr-index:end -->';

const STATUS_RE =
  /^Status: (Accepted|Proposed|Completed|Superseded by (\d{4}))(?: \((\d{4}-\d{2}-\d{2})\))?$/;
const DATE_RE = /^(?:- \*\*Date:\*\*|Date:)\s*(\d{4}-\d{2}-\d{2})\b/;
const LINK_RE = /\]\(\.?\/?(\d{4})-[\w-]+\.md/g;

export interface Adr {
  number: string;
  file: string;
  title: string;
  status: string;
  statusDate: string | null;
  date: string | null;
  supersededBy: string | null;
}

export interface Change {
  target: string;
  by: string;
  kind: 'whole' | 'in part' | 'amends';
}

/** The header is everything above the first second-level heading. */
function headerLines(text: string): string[] {
  const lines = text.split(/\r?\n/);
  const end = lines.findIndex((line, i) => i > 0 && line.startsWith('## '));
  return end === -1 ? lines : lines.slice(0, end);
}

/**
 * The header's prose as sentences. Prettier wraps long lines, so a clause such as "Supersedes the
 * estimates in [0013](...)" can put its link on the next line: paragraphs (and blockquotes) are
 * joined first.
 */
function headerSentences(header: readonly string[]): string[] {
  const paragraphs: string[] = [];
  let current: string[] = [];
  const flush = (): void => {
    if (current.length > 0) paragraphs.push(current.join(' '));
    current = [];
  };
  for (const raw of header) {
    const quoted = raw.replace(/^>\s?/, '');
    if (quoted.trim() === '' || raw.startsWith('# ')) {
      flush();
      continue;
    }
    // A list item or a header field (`Date:`, `Status:`, `Supersedes ...`) starts a new paragraph.
    if (
      /^\s*[-*] /.test(quoted) ||
      /^(Date|Status|Context|Supersedes|Superseded|Amends|Amended)\b/.test(quoted)
    )
      flush();
    current.push(
      quoted
        .replace(/^\s*[-*]\s+/, '')
        .replace(/\*\*/g, '')
        .trim(),
    );
  }
  flush();
  return paragraphs.flatMap((p) => p.split(/(?<=[.;])\s+(?=[A-Z[])/)).map((s) => s.trim());
}

function cleanTitle(heading: string, number: string): string {
  return heading
    .replace(/^#\s+/, '')
    .replace(new RegExp(`^(?:ADR\\s+)?${number}\\s*(?:—|:|-)\\s*`), '')
    .trim();
}

export function parseAdr(
  file: string,
  text: string,
): { adr: Adr; changes: Change[]; errors: string[] } {
  const number = file.slice(0, 4);
  const errors: string[] = [];
  const header = headerLines(text);
  const heading = header.find((line) => line.startsWith('# '));
  if (heading === undefined) errors.push(`${file}: no "# " title line`);

  const standard = header.filter((line) => STATUS_RE.test(line));
  let status = '';
  let statusDate: string | null = null;
  let supersededBy: string | null = null;
  if (standard.length !== 1) {
    errors.push(
      `${file}: needs exactly one line "Status: <Accepted|Proposed|Completed|Superseded by NNNN> (YYYY-MM-DD)" above the first "## " heading (qualifiers go on a "Status note:" line), found ${standard.length}`,
    );
  } else {
    const match = STATUS_RE.exec(standard[0]!)!;
    status = match[1]!;
    supersededBy = match[2] ?? null;
    statusDate = match[3] ?? null;
  }

  let date: string | null = null;
  for (const line of header) {
    const match = DATE_RE.exec(line);
    if (match) {
      date = match[1]!;
      break;
    }
  }

  const changes: Change[] = [];
  if (supersededBy !== null) changes.push({ target: number, by: supersededBy, kind: 'whole' });
  for (const sentence of headerSentences(header)) {
    const targets = [...sentence.matchAll(LINK_RE)].map((m) => m[1]!).filter((n) => n !== number);
    if (targets.length === 0) continue;
    if (/^(Superseded in part by|Amended by)\b/.test(sentence)) {
      const kind = sentence.startsWith('Amended') ? 'amends' : 'in part';
      for (const by of targets) changes.push({ target: number, by, kind });
    } else if (/^(Supersedes|Amends)\b/.test(sentence)) {
      // "Supersedes [0012](...)" with the link straight after the verb replaces that ADR whole;
      // "Supersedes parts of", "Supersedes in part" or "Supersedes the note in" does not.
      const kind = sentence.startsWith('Amends')
        ? 'amends'
        : /^Supersedes:?\s*\[/.test(sentence)
          ? 'whole'
          : 'in part';
      for (const target of targets) changes.push({ target, by: number, kind });
    }
  }

  return {
    adr: {
      number,
      file,
      title: heading === undefined ? file : cleanTitle(heading, number),
      status,
      statusDate,
      date,
      supersededBy,
    },
    changes,
    errors,
  };
}

export interface AdrSource {
  file: string;
  text: string;
}

export function readAdrs(dir: string): AdrSource[] {
  return readdirSync(dir)
    .filter((f) => /^\d{4}-.+\.md$/.test(f))
    .sort()
    .map((file) => ({ file, text: readFileSync(join(dir, file), 'utf8') }));
}

export function buildTable(sources: readonly AdrSource[]): { table: string; errors: string[] } {
  const errors: string[] = [];
  const adrs: Adr[] = [];
  const changes: Change[] = [];
  const seen = new Map<string, Adr>();
  for (const { file, text } of [...sources].sort((a, b) => a.file.localeCompare(b.file))) {
    const parsed = parseAdr(file, text);
    const other = seen.get(parsed.adr.number);
    if (other !== undefined)
      errors.push(`ADR number ${parsed.adr.number} is used twice: ${other.file} and ${file}`);
    seen.set(parsed.adr.number, parsed.adr);
    adrs.push(parsed.adr);
    changes.push(...parsed.changes);
    errors.push(...parsed.errors);
  }

  const changedBy = new Map<string, Set<string>>();
  for (const change of changes) {
    const target = seen.get(change.target);
    if (target === undefined || !seen.has(change.by)) {
      const missing = target === undefined ? change.target : change.by;
      errors.push(
        `ADR ${change.by} and ${change.target} are linked, but ADR ${missing} does not exist`,
      );
      continue;
    }
    if (change.kind === 'whole' && target.supersededBy !== change.by) {
      errors.push(
        `ADR ${change.by} supersedes ${change.target} whole, but ${target.file} does not say "Status: Superseded by ${change.by}"; write "Supersedes in part" or update its status`,
      );
    }
    const set = changedBy.get(change.target) ?? new Set<string>();
    set.add(`${change.by} (${change.kind})`);
    changedBy.set(change.target, set);
  }

  const rows = adrs.map((adr) => {
    const status = adr.statusDate === null ? adr.status : `${adr.status} (${adr.statusDate})`;
    const cells = [
      `[${adr.number}](${adr.file})`,
      adr.title.replace(/\|/g, '\\|'),
      status,
      adr.date ?? '—',
      [...(changedBy.get(adr.number) ?? [])].sort().join(', ') || '—',
    ];
    return `| ${cells.join(' | ')} |`;
  });
  const table = [
    '| ADR | Title | Status | Date | Superseded or amended by |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
  ].join('\n');
  return { table, errors };
}

async function render(current: string, table: string): Promise<string> {
  const start = current.indexOf(START);
  const end = current.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`docs/decisions/README.md must contain the markers:\n${START}\n${END}`);
  }
  const next = `${current.slice(0, start + START.length)}\n\n${table}\n\n${current.slice(end)}`;
  return format(next, { filepath: README });
}

async function main(): Promise<void> {
  const check = process.argv.includes('--check');
  const { table, errors } = buildTable(readAdrs(DIR));
  const current = readFileSync(README, 'utf8');
  const next = await render(current, table);
  if (check) {
    if (next !== current) errors.push('docs/decisions/README.md is stale: run `bun run adr:index`');
    if (errors.length > 0) {
      for (const error of errors) console.error(`adr-index: ${error}`);
      process.exit(1);
    }
    console.log(`adr-index: ${table.split('\n').length - 2} ADRs, index up to date`);
    return;
  }
  if (errors.length > 0) {
    for (const error of errors) console.error(`adr-index: ${error}`);
    process.exit(1);
  }
  writeFileSync(README, next);
  console.log(`adr-index: wrote ${table.split('\n').length - 2} ADRs to docs/decisions/README.md`);
}

if (import.meta.main) await main();
