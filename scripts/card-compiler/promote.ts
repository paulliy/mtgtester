export const COMPILED_DIR = 'packages/engine/src/cards/overrides/compiled';
const GENERATED =
  '// Generated by `bun run scripts/card-compiler/run.ts promote`. Do not edit by hand.';

const sha256 = (data: string | Buffer): string => createHash('sha256').update(data).digest('hex');

/** The hash `retire` compares against: behavior only, ability lists unordered. */
export function behaviorSha256(definition: CardDefinition): string {
  return sha256(canonicalBehavior(definition, { unorderedAbilities: true }));
}

// ── The generated module ──────────────────────────────────────────────────────────────────────

const BATCH_ID = /^[a-z0-9]+(-[a-z0-9]+)*$/;

/** A batch id as a TypeScript identifier: `trial-01` becomes `BATCH_TRIAL_01`. */
function batchConst(id: string): string {
  if (!BATCH_ID.test(id))
    throw new Error(`batch id "${id}" must be lowercase letters, digits and single hyphens`);
  return `BATCH_${id.toUpperCase().replace(/-/g, '_')}`;
}

/**
 * The whole compiled registry as one module: a constant per batch, in batch-id order, each with
 * its cards in name order. It is one file on purpose. The viewer-evidence generators list every
 * engine source they depend on (`SOURCE_FILES`), so a module per batch would mean editing those
 * lists at every promotion; one module is listed once, and a promotion changes only its content.
 */
export function renderCompiledModule(batches: readonly CompiledBatch[]): string {
  const kept = batches
    .filter((batch) => batch.cards.length > 0)
    .sort((a, b) => a.id.localeCompare(b.id));
  const constants = kept
    .map((batch) => {
      const cards = [...batch.cards].sort((a, b) => a.name.localeCompare(b.name));
      return `const ${batchConst(batch.id)}: readonly CompiledCard[] = ${JSON.stringify(cards, null, 2)};\n\n`;
    })
    .join('');
  const entries = kept
    .map((batch) => `  { id: '${batch.id}', cards: ${batchConst(batch.id)} },\n`)
    .join('');
  const types = kept.length === 0 ? 'CompiledBatch' : 'CompiledBatch, CompiledCard';
  return `${GENERATED}
import type { ${types} } from './types';

${constants}/** Every promoted batch of compiled cards, in batch-id order. */
export const COMPILED_BATCHES: readonly CompiledBatch[] = [${entries === '' ? '' : `\n${entries}`}];
`;
}

/** Write the registry to `dir/index.ts` and format it. */
export function writeBatches(dir: string, batches: readonly CompiledBatch[]): void {
  writeFileSync(`${dir}/index.ts`, renderCompiledModule(batches));
  runPrettier([`${dir}/index.ts`]);
}

// ── Choosing what to promote ──────────────────────────────────────────────────────────────────

export interface PromotionContext {
  /** Cards already in a compiled batch, by Oracle id. */
  promoted: ReadonlySet<string>;
  /** Oracle ids that have an override which is not a compiled card. */
  hasAuthoredOverride: (oracleId: string) => boolean;
  pinned: (name: string) => PinnedRow | undefined;
  /** The patch file's bytes, or null when the file is gone. */
  readPatch: (path: string) => Buffer | null;
}

export interface Refusal {
  name: string;
  source: string;
  reason: string;
}

/** Predefined tokens (CR 111.10), whose name alone fixes what they are. */
const PREDEFINED_TOKENS = new Set([
  'Treasure',
  'Food',
  'Clue',
  'Blood',
  'Gold',
  'Map',
  'Powerstone',
  'Incubator',
  'Shard',
  'Junk',
  'Walker',
  'Lander',
  'Mutagen',
]);

const sortedJson = (value: unknown): string =>
  JSON.stringify(value, (_key, entry: unknown) =>
    entry !== null && typeof entry === 'object' && !Array.isArray(entry)
      ? Object.fromEntries(
          Object.entries(entry as Record<string, unknown>).sort(([x], [y]) => x.localeCompare(y)),
        )
      : entry,
  );

/**
 * The catalog's token of each predefined name (`cards/tokens.ts`), as key-sorted JSON. Only a
 * predefined token (CR 111.10: Treasure, Food, Clue, ...) is fully determined by its name; a
 * "1/1 red and white Soldier with haste" is a different token from the catalog's white Soldier.
 */
const CATALOG_TOKENS = new Map<string, string>(
  Object.values(TOKEN_CATALOG)
    .filter(
      (entry): entry is { name: string; power?: unknown } =>
        entry !== null &&
        typeof entry === 'object' &&
        typeof (entry as { name?: unknown }).name === 'string' &&
        Array.isArray((entry as { types?: unknown }).types),
    )
    .filter((entry) => PREDEFINED_TOKENS.has(entry.name))
    .map((entry) => [entry.name, sortedJson(entry)]),
);

/**
 * Names of the tokens in a patch that share a name with a catalog token and differ from it. The
 * generated module is exempt from the lint rule that sends authored cards to the catalog, so this
 * is what stops a compiled card from making a Treasure without its sacrifice cost.
 */
export function tokenDrift(def: unknown): string[] {
  const drifted = new Set<string>();
  const walk = (value: unknown): void => {
    if (Array.isArray(value)) return value.forEach(walk);
    if (value === null || typeof value !== 'object') return;
    const record = value as Record<string, unknown>;
    if (typeof record['name'] === 'string' && Array.isArray(record['types'])) {
      const catalog = CATALOG_TOKENS.get(record['name']);
      if (catalog !== undefined && catalog !== sortedJson(record)) drifted.add(record['name']);
    }
    Object.values(record).forEach(walk);
  };
  walk(def);
  return [...drifted].sort();
}

/**
 * Split the accepted queue entries into cards to promote and cards refused, with the reason.
 * Entries that were never accepted are not mentioned: they are simply still waiting.
 */
export function selectForPromotion(
  entries: readonly QueueEntry[],
  context: PromotionContext,
  options: { trial?: string } = {},
): { cards: CompiledCard[]; refused: Refusal[] } {
  const accepted = entries.filter(
    (entry) =>
      entry.review?.verdict === 'accepted' &&
      (options.trial === undefined || entry.trial === options.trial),
  );
  const acceptedPerCard = new Map<string, number>();
  for (const entry of accepted)
    acceptedPerCard.set(entry.oracleId, (acceptedPerCard.get(entry.oracleId) ?? 0) + 1);

  const cards: CompiledCard[] = [];
  const refused: Refusal[] = [];
  for (const entry of accepted) {
    const refuse = (reason: string): void => {
      refused.push({ name: entry.name, source: entry.source, reason });
    };
    if (context.promoted.has(entry.oracleId)) continue;
    if (entry.status !== 'compiled-checked' && entry.status !== 'meaning-differs') {
      refuse(`its checks ended as ${entry.status}`);
      continue;
    }
    if (entry.smokeExercised !== true) {
      refuse('no smoke game resolved its ability or spell');
      continue;
    }
    if ((acceptedPerCard.get(entry.oracleId) ?? 0) > 1) {
      refuse('more than one accepted patch claims this card; reject all but one');
      continue;
    }
    if (context.hasAuthoredOverride(entry.oracleId)) {
      refuse('the card already has an authored override');
      continue;
    }
    if (entry.patch === null || entry.patchSha256 === null) {
      refuse('the queue entry has no patch file');
      continue;
    }
    const bytes = context.readPatch(entry.patch);
    if (bytes === null) {
      refuse(`the patch file ${entry.patch} is missing`);
      continue;
    }
    if (sha256(bytes) !== entry.patchSha256) {
      refuse('the patch file changed after it was reviewed');
      continue;
    }
    const row = context.pinned(entry.name);
    if (row === undefined || row.card.oracleId !== entry.oracleId) {
      refuse('the card is not in the pinned pool under this Oracle id');
      continue;
    }
    const target = compileTarget(row);
    if (target === null) {
      refuse('the interpreter now models the card without the patch');
      continue;
    }
    const patch = JSON.parse(bytes.toString('utf8')) as PatchFile;
    if (
      patch.oracleId !== entry.oracleId ||
      JSON.stringify(patch.handledLines) !== JSON.stringify(target.lines)
    ) {
      refuse('the lines the patch was written for are no longer the unparsed lines of the card');
      continue;
    }
    const drift = tokenDrift(patch.def);
    if (drift.length > 0) {
      refuse(`its ${drift.join(', ')} token differs from the token catalog`);
      continue;
    }
    const applied = applyPatch(target, patch.def);
    if (!applied.ok || applied.definition === null) {
      refuse(`the patch no longer validates: ${applied.issues.join('; ')}`);
      continue;
    }
    cards.push({
      oracleId: entry.oracleId,
      name: entry.name,
      handledLines: patch.handledLines,
      def: patch.def,
      source: entry.source,
      trial: entry.trial,
      patchSha256: entry.patchSha256,
      behaviorSha256: behaviorSha256(applied.definition),
      acceptedBy: entry.review!.by,
    });
  }
  return { cards, refused };
}

// ── Additive-only verification ────────────────────────────────────────────────────────────────

/** The committed nets a promotion may only add to. */
export const VERIFIED_FILES = {
  overrideDefs: 'packages/engine/tests/fixtures/override-defs.json',
  interpretDefs: 'packages/engine/tests/fixtures/interpret-defs.json',
  interpretDefsPinned: 'packages/engine/tests/fixtures/interpret-defs-pinned.json',
  corpusOutcomes: 'packages/engine/tests/fixtures/one-line-outcomes.tsv',
  modeled: 'packages/server/fixtures/edhrec-modeled.json',
} as const;

export type VerifiedTexts = Record<keyof typeof VERIFIED_FILES, string>;

export interface VerifyInput {
  base: VerifiedTexts;
  head: VerifiedTexts;
  /** Engine source paths that differ between the base and the working tree. */
  changedEngineSources: readonly string[];
  /** Compiled cards in the base's override snapshot are the already-promoted ones. */
  compiled: readonly { oracleId: string; name: string }[];
}

interface SnapshotEntry {
  oracleId: string;
  name?: string;
}

const byOracleId = (text: string): Map<string, string> =>
  new Map((JSON.parse(text) as SnapshotEntry[]).map((e) => [e.oracleId, JSON.stringify(e)]));

/** Every way the head differs from the base beyond adding the newly promoted cards. */
export function additiveViolations(input: VerifyInput): {
  promoted: string[];
  violations: string[];
} {
  const violations: string[] = [];
  const baseOverrides = byOracleId(input.base.overrideDefs);
  const headOverrides = byOracleId(input.head.overrideDefs);
  const promoted = input.compiled.filter((card) => !baseOverrides.has(card.oracleId));
  const promotedIds = new Set(promoted.map((card) => card.oracleId));
  // `extendCard` also registers each card under the fixture id derived from its name.
  const registeredIds = new Set([
    ...promotedIds,
    ...promoted.map((card) => fixtureOracleId(card.name)),
  ]);
  const promotedNames = new Set(promoted.map((card) => card.name));

  for (const path of input.changedEngineSources)
    if (path !== `${COMPILED_DIR}/index.ts`)
      violations.push(`engine source changed outside the generated compiled module: ${path}`);

  for (const [id, entry] of baseOverrides) {
    const now = headOverrides.get(id);
    if (now === undefined) violations.push(`override snapshot lost ${id}`);
    else if (now !== entry) violations.push(`override snapshot entry changed: ${id}`);
  }
  for (const id of headOverrides.keys())
    if (!baseOverrides.has(id) && !registeredIds.has(id))
      violations.push(`override snapshot gained ${id}, which is not a promoted compiled card`);
  for (const card of promoted)
    if (!headOverrides.has(card.oracleId))
      violations.push(`override snapshot is stale: ${card.name} is promoted but not in it`);

  for (const key of ['interpretDefs', 'interpretDefsPinned'] as const) {
    const before = byOracleId(input.base[key]);
    const after = byOracleId(input.head[key]);
    for (const [id, entry] of before) {
      const now = after.get(id);
      if (now === undefined) violations.push(`${VERIFIED_FILES[key]} lost ${id}`);
      else if (now !== entry && !promotedIds.has(id))
        violations.push(`${VERIFIED_FILES[key]} changed for ${id}, which was not promoted`);
    }
    for (const id of after.keys())
      if (!before.has(id)) violations.push(`${VERIFIED_FILES[key]} gained ${id}`);
  }
  if (input.base.corpusOutcomes !== input.head.corpusOutcomes)
    violations.push(`${VERIFIED_FILES.corpusOutcomes} changed`);

  interface Ratchet {
    fixtureSha256: string;
    modeled: string[];
    fingerprints?: Record<string, string>;
  }
  const before = JSON.parse(input.base.modeled) as Ratchet;
  const after = JSON.parse(input.head.modeled) as Ratchet;
  if (before.fixtureSha256 !== after.fixtureSha256)
    violations.push('the pinned Oracle fixture changed');
  if (before.fingerprints === undefined || after.fingerprints === undefined)
    violations.push('the modeled ratchet has no definition fingerprints to compare');
  const nowModeled = new Set(after.modeled);
  const thenModeled = new Set(before.modeled);
  for (const name of before.modeled) {
    if (!nowModeled.has(name)) violations.push(`${name} no longer models`);
    else if (
      before.fingerprints !== undefined &&
      after.fingerprints !== undefined &&
      before.fingerprints[name] !== after.fingerprints[name]
    )
      violations.push(`${name} still models, with a different definition`);
  }
  for (const name of after.modeled)
    if (!thenModeled.has(name) && !promotedNames.has(name))
      violations.push(`${name} newly models, and is not a promoted compiled card`);
  for (const name of promotedNames)
    if (!nowModeled.has(name))
      violations.push(
        `the modeled ratchet is stale or ${name} does not model: it is promoted but not recorded`,
      );

  return { promoted: [...promotedNames].sort(), violations };
}

// ── Commands ──────────────────────────────────────────────────────────────────────────────────

function flag(args: readonly string[], name: string): string | undefined {
  const index = args.indexOf(`--${name}`);
  if (index < 0) return undefined;
  const value = args[index + 1];
  if (value === undefined || value.startsWith('--')) throw new Error(`--${name} needs a value`);
  return value;
}

function loadQueue(): { schemaVersion: number; cards: QueueEntry[] } {
  return JSON.parse(readFileSync(QUEUE_PATH, 'utf8')) as {
    schemaVersion: number;
    cards: QueueEntry[];
  };
}

function allCompiled(batches: readonly CompiledBatch[]): Map<string, CompiledCard> {
  return new Map(batches.flatMap((batch) => batch.cards).map((card) => [card.oracleId, card]));
}

/** `review <name> --verdict accepted|rejected --by <who> [--source <tag>] [--note <text>]` */
export function reviewCommand(args: readonly string[]): void {
  const name = args[0];
  const verdict = flag(args, 'verdict');
  const by = flag(args, 'by');
  const source = flag(args, 'source');
  const note = flag(args, 'note');
  if (name === undefined || by === undefined || (verdict !== 'accepted' && verdict !== 'rejected'))
    throw new Error(
      'usage: run.ts review <name> --verdict accepted|rejected --by <who> [--source <tag>] [--note <text>]',
    );
  const queue = loadQueue();
  const matches = queue.cards.filter(
    (entry) => entry.name === name && (source === undefined || entry.source === source),
  );
  if (matches.length === 0) throw new Error(`no queue entry for "${name}"`);
  if (matches.length > 1)
    throw new Error(
      `"${name}" has ${matches.length} patches (${matches.map((entry) => entry.source).join(', ')}); pass --source`,
    );
  const entry = matches[0]!;
  if (entry.patch === null || entry.patchSha256 === null)
    throw new Error(`"${name}" has no patch file to review`);
  if (sha256(readFileSync(entry.patch)) !== entry.patchSha256)
    throw new Error(`${entry.patch} changed since the queue was built; run \`run.ts queue\` again`);
  entry.review = { verdict, by, ...(note === undefined ? {} : { note }) };
  writeFileSync(QUEUE_PATH, `${JSON.stringify(queue, null, 2)}\n`);
  runPrettier([QUEUE_PATH]);
  console.log(`${name} (${entry.source}): ${verdict} by ${by}`);
}

/** `promote <batch-id> [--trial <dir>] [--dry-run]` */
export function promoteCommand(args: readonly string[]): void {
  const id = args[0];
  if (id === undefined || id.startsWith('--'))
    throw new Error('usage: run.ts promote <batch-id> [--trial <dir>] [--dry-run]');
  batchConst(id);
  const trial = flag(args, 'trial');
  const compiled = allCompiled(COMPILED_BATCHES);
  const byName = new Map(pinnedPool().map((row) => [row.card.name, row]));
  const { cards, refused } = selectForPromotion(
    loadQueue().cards,
    {
      promoted: new Set(compiled.keys()),
      hasAuthoredOverride: (oracleId) =>
        getOverride(oracleId as Parameters<typeof getOverride>[0]) !== undefined &&
        !compiled.has(oracleId),
      pinned: (name) => byName.get(name),
      readPatch: (path) => (existsSync(path) ? readFileSync(path) : null),
    },
    trial === undefined ? {} : { trial },
  );
  for (const refusal of refused)
    console.log(`refused: ${refusal.name} (${refusal.source}): ${refusal.reason}`);
  if (cards.length === 0) {
    console.log('nothing to promote');
    return;
  }
  for (const card of cards) console.log(`promote: ${card.name} (${card.source})`);
  if (args.includes('--dry-run')) {
    console.log(`dry run: ${cards.length} cards would join batch ${id}`);
    return;
  }
  const existing = COMPILED_BATCHES.find((batch) => batch.id === id);
  const after: CompiledBatch[] = [
    ...COMPILED_BATCHES.filter((batch) => batch.id !== id),
    { id, cards: [...(existing?.cards ?? []), ...cards] },
  ];
  writeBatches(COMPILED_DIR, after);
  console.log(
    `${cards.length} cards promoted into batch ${id} of ${COMPILED_DIR}/index.ts. Next, in this order:\n` +
      '  bun run snapshots:write\n' +
      '  bun run coverage:pin --ratchet\n' +
      '  bun run modelled-cards\n' +
      '  bun run ai-bench refresh --suite core-fast --write\n' +
      '  bun run scripts/card-compiler/run.ts verify',
  );
}

/** `retire <name>`: take one promoted card back out, and say how the interpreter reads it now. */
export function retireCommand(args: readonly string[]): void {
  const name = args[0];
  if (name === undefined) throw new Error('usage: run.ts retire <name>');
  const batch = COMPILED_BATCHES.find((entry) => entry.cards.some((card) => card.name === name));
  if (batch === undefined) throw new Error(`"${name}" is not a promoted compiled card`);
  const card = batch.cards.find((entry) => entry.name === name)!;
  const after = COMPILED_BATCHES.map((entry) =>
    entry.id === batch.id
      ? { id: entry.id, cards: entry.cards.filter((other) => other.name !== name) }
      : entry,
  );
  writeBatches(COMPILED_DIR, after);
  console.log(`retired ${name} from batch ${batch.id}`);

  const row = pinnedPool().find((entry) => entry.card.name === name);
  if (row === undefined) return;
  const stranded = strandedReading(row, card);
  if (stranded === 'unmodeled')
    console.log(`${name} is unmodeled without the patch: the engine now halts on it.`);
  else if (stranded === 'agrees')
    console.log(
      `${name}: the interpreter now models it alone, with the same behavior as the patch.`,
    );
  else
    console.log(
      `${name}: the interpreter now models it alone, with DIFFERENT behavior from the patch. ` +
        'One of the two readings is wrong; decide which before merging the grammar change.',
    );
  console.log('Regenerate: bun run snapshots:write && bun run coverage:pin --ratchet');
}

/** How the interpreter reads a compiled card with its patch set aside. */
export function strandedReading(
  row: PinnedRow,
  card: Pick<CompiledCard, 'oracleId' | 'behaviorSha256'>,
  interpretAlone: (row: PinnedRow) => CardDefinition = interpretWithoutCompiled(card.oracleId),
): 'unmodeled' | 'agrees' | 'differs' {
  const alone = interpretAlone(row);
  if (!alone.modeled) return 'unmodeled';
  return behaviorSha256(alone) === card.behaviorSha256 ? 'agrees' : 'differs';
}

/** Interpret the card with its override (the compiled patch, in this process) set aside. */
function interpretWithoutCompiled(oracleId: string): (row: PinnedRow) => CardDefinition {
  return (row) => {
    const id = oracleId as Parameters<typeof getOverride>[0];
    const registered = getOverride(id);
    if (registered === undefined) return interpretCard(row.card);
    unregisterOverride(id);
    try {
      return interpretCard(row.card);
    } finally {
      registerOverride(registered);
    }
  };
}

function git(args: string[]): string {
  return execFileSync('git', args, { encoding: 'utf8', maxBuffer: 1 << 28 });
}

/** `verify [--base <sha>]`: fail unless the working tree only adds promoted cards to the base. */
export function verifyCommand(args: readonly string[]): void {
  const base = flag(args, 'base') ?? git(['merge-base', 'HEAD', 'origin/main']).trim();
  const read = (source: 'base' | 'head'): VerifiedTexts =>
    Object.fromEntries(
      Object.entries(VERIFIED_FILES).map(([key, path]) => [
        key,
        source === 'base' ? git(['show', `${base}:${path}`]) : readFileSync(path, 'utf8'),
      ]),
    ) as VerifiedTexts;
  const changedEngineSources = [
    ...git(['diff', '--name-only', base, '--', 'packages/engine/src']).split('\n'),
    ...git(['ls-files', '--others', '--exclude-standard', '--', 'packages/engine/src']).split('\n'),
  ].filter((path) => path !== '');
  const { promoted, violations } = additiveViolations({
    base: read('base'),
    head: read('head'),
    changedEngineSources,
    compiled: [...allCompiled(COMPILED_BATCHES).values()],
  });
  for (const violation of violations) console.error(`not additive: ${violation}`);
  if (violations.length > 0) {
    console.error(`${violations.length} problems against base ${base.slice(0, 9)}`);
    process.exit(1);
  }
  console.log(
    `additive against ${base.slice(0, 9)}: ${promoted.length} cards promoted, nothing else changed.`,
  );
}
