/** Riders of Rohan (evasion-and-blocking batch): scenarios in ../../scenarios/riders-of-rohan.json. */
import { describe, expect, it } from 'vitest';
import { loadScenarioFile, runScenario, scenarioFailures } from '../../scenario/runner';

const file = loadScenarioFile(new URL('../../scenarios/riders-of-rohan.json', import.meta.url));

describe('Riders of Rohan', () => {
  it.each(file.scenarios.map((entry) => [entry.id, entry] as const))('%s', (_id, entry) => {
    expect(scenarioFailures(runScenario(file, entry), entry)).toEqual([]);
  });
});
