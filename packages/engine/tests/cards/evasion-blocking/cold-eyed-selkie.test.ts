/** Cold-Eyed Selkie: scenarios in ../../scenarios/cold-eyed-selkie.json. */
import { describe, expect, it } from 'vitest';
import { loadScenarioFile, runScenario, scenarioFailures } from '../../scenario/runner';

const file = loadScenarioFile(new URL('../../scenarios/cold-eyed-selkie.json', import.meta.url));

describe('Cold-Eyed Selkie', () => {
  it.each(file.scenarios.map((entry) => [entry.id, entry] as const))('%s', (_id, entry) => {
    expect(scenarioFailures(runScenario(file, entry), entry)).toEqual([]);
  });
});
