/** Shadowmage Infiltrator: scenarios in ../../scenarios/shadowmage-infiltrator.json. */
import { describe, expect, it } from 'vitest';
import { loadScenarioFile, runScenario, scenarioFailures } from '../../scenario/runner';

const file = loadScenarioFile(
  new URL('../../scenarios/shadowmage-infiltrator.json', import.meta.url),
);

describe('Shadowmage Infiltrator', () => {
  it.each(file.scenarios.map((entry) => [entry.id, entry] as const))('%s', (_id, entry) => {
    expect(scenarioFailures(runScenario(file, entry), entry)).toEqual([]);
  });
});
