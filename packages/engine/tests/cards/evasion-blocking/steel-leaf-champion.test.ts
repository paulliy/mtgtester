/** Steel Leaf Champion (engine-feature plan PR 2): scenarios in ../../scenarios/steel-leaf-champion.json. */
import { describe, expect, it } from 'vitest';
import { loadScenarioFile, runScenario, scenarioFailures } from '../../scenario/runner';

const file = loadScenarioFile(new URL('../../scenarios/steel-leaf-champion.json', import.meta.url));

describe('Steel Leaf Champion', () => {
  it.each(file.scenarios.map((entry) => [entry.id, entry] as const))('%s', (_id, entry) => {
    expect(scenarioFailures(runScenario(file, entry), entry)).toEqual([]);
  });
});
