/** Nexus of Fate (graveyard and hand batch): scenarios in ../../scenarios/nexus-of-fate.json. */
import { describe, expect, it } from 'vitest';
import { loadScenarioFile, runScenario, scenarioFailures } from '../../scenario/runner';

const file = loadScenarioFile(new URL('../../scenarios/nexus-of-fate.json', import.meta.url));

describe('Nexus of Fate', () => {
  it.each(file.scenarios.map((entry) => [entry.id, entry] as const))('%s', (_id, entry) => {
    expect(scenarioFailures(runScenario(file, entry), entry)).toEqual([]);
  });
});
