const fixture = JSON.parse(
  readFileSync('packages/engine/tests/fixtures/bug-hunt-oracle.json', 'utf8'),
) as { cards: { card: OracleCard }[] };
function real(name: string): OracleCard {
  const card = fixture.cards
    .map((entry) => entry.card)
    .find((candidate) => candidate.name === name);
  if (!card) throw new Error(`Missing Oracle fixture: ${name}`);
  expect(interpretCard(card).modeled, name).toBe(true);
  return card;
}
function pod() {
  const ctx = createGame(gameConfig([0, 1, 2, 3].map(() => ({ cards: copies(8, forest) }))));
  Object.assign(ctx.state, {
    currentTurnPlayer: 'P1',
    activePlayerIndex: 0,
    turnNumber: 4,
    phase: 'precombatMain',
    step: null,
  });
  return ctx;
}
function respond(request: DecisionRequest) {
  const action =
    request.legalActions.find((candidate) => candidate.type === 'pass') ?? request.legalActions[0]!;
  return {
    requestId: request.requestId,
    actionId: action.id,
    targets: action.targets?.map((slot) => ({ slot: slot.slot, choice: slot.options[0]! })) ?? [],
  };
}
function cast(
  ctx: ReturnType<typeof pod>,
  playerId: string,
  name: string,
  targets: Map<number, string>,
) {
  const player = ctx.state.players.find((candidate) => candidate.id === playerId)!;
  const option = computePriorityOptions(ctx, player).find(
    (candidate) => candidate.type === 'castSpell' && candidate.description.includes(name),
  );
  expect(option, `${name} must be offered legally`).toBeDefined();
  pump(
    applyPriorityAction(ctx, player, option!.payload as PriorityActionPayload, {
      index: 0,
      targets,
    }),
  );
}
/** Legal attached initial board; the tested ETB is generated by the ordinary zone mover. */
function attachedChains(ctx: ReturnType<typeof pod>, hostId: string, victimId: string) {
  const card = conjure(ctx, 'P1', real('Chains of Custody'), 'hand');
  const aura = pump(moveObject(ctx, card, { zone: 'battlefield', controllerId: 'P1' })).value!;
  if (!('attachedTo' in aura)) throw new Error('Chains did not enter');
  aura.attachedTo = hostId;
  pump(priorityCheckpoint(ctx), () => ({ index: 0, targets: new Map([[0, victimId]]) }));
  expect(ctx.state.stack.at(-1)?.sourceCardId).toBe(aura.cardId);
  pump(resolveTopOfStack(ctx));
  expect(
    ctx.state.exile.some(
      (candidate) => candidate.cardId === ctx.state.exiledUntilLeaves[aura.cardId]?.[0]?.cardId,
    ),
  ).toBe(true);
  return aura;
}

describe('linked exile boundaries', () => {
  it.each([
    ['Chains of Custody', 'P1'],
    ['Coercive Impetus', 'P2'],
  ])('a normally cast %s must enter attached to the chosen host', (name, hostController) => {
    const card = real(name);
    const engine = new Engine(
      gameConfig([
        { cards: [card, bear(), ...copies(2, plains), swamp(), ...copies(5, forest)] },
        { cards: [bear(), ...copies(8, forest)] },
        { cards: copies(8, forest) },
        { cards: copies(8, forest) },
      ]),
      {
        preparedScenario: {
          currentTurnPlayer: 'P1',
          phase: 'precombatMain',
          step: null,
          turnNumber: 4,
          hand: [{ playerId: 'P1', cardNames: [name] }],
          battlefield: [
            { playerId: 'P1', cardNames: ['Test Bear', 'Plains', 'Plains', 'Swamp'] },
            { playerId: 'P2', cardNames: ['Test Bear'] },
          ],
        },
      },
    );
    const host = engine
      .getState()
      .battlefield.find((p) => p.name === 'Test Bear' && p.controllerId === hostController)!;
    let castCount = 0;
    let _offeredTargets: unknown;
    for (let iteration = 0; iteration < 60; iteration++) {
      const step = engine.advance();
      if (step.kind === 'gameOver') break;
      if (step.kind !== 'decision') continue;
      const request = step.request;
      const option =
        castCount === 0 &&
        request.decidingPlayer === 'P1' &&
        request.legalActions.find((a) => a.type === 'castSpell' && a.description.includes(name));
      if (option) {
        _offeredTargets = option.targets;
        engine.submit({
          requestId: request.requestId,
          actionId: option.id,
          targets: option.targets?.map((slot) => ({ slot: slot.slot, choice: host.id })) ?? [],
        });
        castCount++;
      } else engine.submit(respond(request));
    }
    expect(castCount).toBe(1);
    const state = engine.getState();
    const live = state.battlefield.find((p) => p.name === name);
    expect(live?.attachedTo).toBe(host.id);
    expect(state.players[0]!.graveyard.some((candidate) => candidate.name === name)).toBe(false);
  });

  it('a real modeled Aura cannot be cast when no legal enchant target exists', () => {
    const card = real('Coercive Impetus');
    const engine = new Engine(
      gameConfig([
        { cards: [card, ...copies(3, swamp), ...copies(5, forest)] },
        { cards: copies(8, forest) },
      ]),
      {
        preparedScenario: {
          currentTurnPlayer: 'P1',
          phase: 'precombatMain',
          step: null,
          turnNumber: 4,
          hand: [{ playerId: 'P1', cardNames: [card.name] }],
          battlefield: [{ playerId: 'P1', cardNames: ['Swamp', 'Swamp', 'Swamp'] }],
        },
      },
    );
    const ctx = (engine as unknown as { ctx: ReturnType<typeof pod> }).ctx;
    const offered = computePriorityOptions(ctx, ctx.state.players[0]!).find(
      (a) => a.type === 'castSpell' && a.description.includes(card.name),
    );
    expect(offered).toBeUndefined();
  });

  it('a normally cast Chains must not exile after the Aura has already left', () => {
    const chains = real('Chains of Custody');
    const removal = {
      ...bolt(),
      oracleId: 'oracle-remove-chains',
      name: 'Test Remove Aura',
      oracleText: 'Destroy target enchantment.',
    };
    const engine = new Engine(
      gameConfig([
        { cards: [chains, bear(), ...copies(3, plains), ...copies(5, forest)] },
        { cards: [bear(), removal, mountain(), ...copies(8, forest)] },
        { cards: copies(8, forest) },
        { cards: copies(8, forest) },
      ]),
      {
        preparedScenario: {
          currentTurnPlayer: 'P1',
          phase: 'precombatMain',
          step: null,
          turnNumber: 4,
          hand: [
            { playerId: 'P1', cardNames: [chains.name] },
            { playerId: 'P2', cardNames: [removal.name] },
          ],
          battlefield: [
            { playerId: 'P1', cardNames: ['Test Bear', 'Plains', 'Plains', 'Plains'] },
            { playerId: 'P2', cardNames: ['Test Bear', 'Mountain'] },
          ],
        },
      },
    );
    const host = engine
      .getState()
      .battlefield.find((p) => p.name === 'Test Bear' && p.controllerId === 'P1')!;
    const victim = engine
      .getState()
      .battlefield.find((p) => p.name === 'Test Bear' && p.controllerId === 'P2')!;
    let castCount = 0;
    let destroyed = false;
    for (let iteration = 0; iteration < 60; iteration++) {
      const step = engine.advance();
      if (step.kind === 'gameOver') break;
      if (step.kind !== 'decision') continue;
      const request = step.request;
      const option =
        castCount === 0 &&
        request.decidingPlayer === 'P1' &&
        request.legalActions.find(
          (a) => a.type === 'castSpell' && a.description.includes(chains.name),
        );
      if (option) {
        engine.submit({
          requestId: request.requestId,
          actionId: option.id,
          targets: option.targets?.map((slot) => ({ slot: slot.slot, choice: host.id })) ?? [],
        });
        castCount++;
      } else {
        const aura = engine.getState().battlefield.find((p) => p.name === chains.name);
        const remove =
          !destroyed &&
          aura &&
          request.decidingPlayer === 'P2' &&
          request.legalActions.find(
            (a) => a.type === 'castSpell' && a.description.includes(removal.name),
          );
        if (remove) {
          engine.submit({
            requestId: request.requestId,
            actionId: remove.id,
            targets: remove.targets?.map((slot) => ({ slot: slot.slot, choice: aura!.id })) ?? [],
          });
          destroyed = true;
        } else engine.submit(respond(request));
      }
    }
    expect(castCount).toBe(1);
    const state = engine.getState();
    expect(destroyed).toBe(true);
    const _sourceLeft = engine.eventsSince(0).find((event) => event.type === 'destroy');
    expect(state.players[0]!.graveyard.some((card) => card.name === chains.name)).toBe(true);
    expect(state.battlefield.some((p) => p.id === victim.id)).toBe(true);
    expect(state.exile.some((p) => p.name === victim.name)).toBe(false);
  });

  it('an established linked-exile effect must return its target when its owner is eliminated', () => {
    const ctx = pod();
    const host = spawn(ctx, 'P1', bear());
    const victim = spawn(ctx, 'P3', bear());
    const aura = attachedChains(ctx, host.id, victim.id);
    spawn(ctx, 'P2', mountain());
    conjure(ctx, 'P2', bolt(), 'hand');
    ctx.state.players[0]!.life = 3;
    cast(ctx, 'P2', 'Test Bolt', new Map([[0, 'P1']]));
    pump(resolveTopOfStack(ctx));
    pump(priorityCheckpoint(ctx));
    expect(ctx.state.eliminatedPlayers).toContain('P1');
    expect(ctx.state.battlefield.some((p) => p.cardId === aura.cardId)).toBe(false);
    expect(ctx.state.battlefield.find((p) => p.cardId === victim.cardId)?.controllerId).toBe('P3');
    expect(ctx.state.exile.some((p) => p.name === victim.name)).toBe(false);
  });

  it('an attached source destroyed above its ETB must not exile the target later', () => {
    const ctx = pod();
    const host = spawn(ctx, 'P1', bear());
    const victim = spawn(ctx, 'P3', bear());
    const card = conjure(ctx, 'P1', real('Chains of Custody'), 'hand');
    const aura = pump(moveObject(ctx, card, { zone: 'battlefield', controllerId: 'P1' })).value!;
    if (!('attachedTo' in aura)) throw new Error('Chains did not enter');
    aura.attachedTo = host.id;
    pump(priorityCheckpoint(ctx), () => ({ index: 0, targets: new Map([[0, victim.id]]) }));
    expect(ctx.state.stack.at(-1)?.sourceCardId).toBe(aura.cardId);
    conjure(
      ctx,
      'P2',
      {
        ...bolt(),
        oracleId: 'oracle-test-remove-aura',
        name: 'Test Remove Aura',
        manaCost: '{R}',
        oracleText: 'Destroy target enchantment.',
      },
      'hand',
    );
    spawn(ctx, 'P2', mountain());
    cast(ctx, 'P2', 'Test Remove Aura', new Map([[0, aura.id]]));
    pump(resolveTopOfStack(ctx));
    expect(ctx.state.battlefield.some((p) => p.cardId === aura.cardId)).toBe(false);
    expect(ctx.state.exiledUntilLeaves[aura.cardId]).toBeUndefined();
    pump(resolveTopOfStack(ctx));
    expect(ctx.state.battlefield.some((p) => p.id === victim.id)).toBe(true);
    expect(ctx.state.exile.some((p) => p.name === victim.name)).toBe(false);
  });

  it('linked-exile return must use the owner rather than the previous controller', () => {
    const ctx = pod();
    ctx.state.currentTurnPlayer = 'P2';
    ctx.state.activePlayerIndex = 1;
    spawn(ctx, 'P2', swamp());
    const victimCard = conjure(ctx, 'P3', bear(), 'graveyard');
    conjure(ctx, 'P2', real('Reanimate'), 'hand');
    cast(ctx, 'P2', 'Reanimate', new Map([[0, victimCard.id]]));
    pump(resolveTopOfStack(ctx));
    const victim = ctx.state.battlefield.find((p) => p.cardId === victimCard.cardId)!;
    expect([victim.ownerId, victim.controllerId]).toEqual(['P3', 'P2']);
    ctx.state.currentTurnPlayer = 'P1';
    ctx.state.activePlayerIndex = 0;
    const host = spawn(ctx, 'P1', bear());
    const aura = attachedChains(ctx, host.id, victim.id);
    // Exercise an ordinary destroy spell against the established source.
    conjure(
      ctx,
      'P2',
      {
        ...bolt(),
        oracleId: 'oracle-test-remove-aura',
        name: 'Test Remove Aura',
        manaCost: '{R}',
        oracleText: 'Destroy target enchantment.',
      },
      'hand',
    );
    spawn(ctx, 'P2', mountain());
    cast(ctx, 'P2', 'Test Remove Aura', new Map([[0, aura.id]]));
    pump(resolveTopOfStack(ctx));
    const returned = ctx.state.battlefield.find((p) => p.cardId === victim.cardId)!;
    expect(returned.id).not.toBe(victim.id);
    expect(returned.controllerId).toBe('P3');
  });
});

it('an Aura fizzles if its enchant target leaves before resolution', () => {
  const ctx = pod();
  const host = spawn(ctx, 'P1', bear());
  for (let i = 0; i < 3; i++) spawn(ctx, 'P1', plains());
  conjure(ctx, 'P1', real('Chains of Custody'), 'hand');
  cast(ctx, 'P1', 'Chains of Custody', new Map([[0, host.id]]));
  pump(moveObject(ctx, host, { zone: 'hand' }));
  pump(resolveTopOfStack(ctx));
  expect(ctx.state.battlefield.some((p) => p.name === 'Chains of Custody')).toBe(false);
  expect(ctx.state.players[0]!.graveyard.some((p) => p.name === 'Chains of Custody')).toBe(true);
  expect(ctx.state.pendingTriggers).toHaveLength(0);
});

it('a returned Aura chooses a host without targeting through hexproof', () => {
  const ctx = pod();
  const host = spawn(ctx, 'P2', {
    ...bear(),
    name: 'Hexproof Bear',
    oracleId: 'hexproof-bear',
    oracleText: 'Hexproof',
  });
  const aura = conjure(ctx, 'P1', real('Coercive Impetus'), 'exile');
  const entered = pump(moveObject(ctx, aura, { zone: 'battlefield' })).value;
  expect(entered && 'attachedTo' in entered ? entered.attachedTo : null).toBe(host.id);
});
